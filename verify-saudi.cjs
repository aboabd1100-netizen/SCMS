const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const memory=new Map();
const storage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
const context=vm.createContext({window:{addEventListener(){}},localStorage:storage,sessionStorage:storage,crypto:require('node:crypto').webcrypto,TextEncoder,structuredClone,console});
vm.runInContext(fs.readFileSync('SC/scms-store.js','utf8'),context);
(async()=>{
 const m=context.window.SCMS;await m.init();
 const before=JSON.parse(JSON.stringify(m.data));
 assert.equal(before.settings.currency,'SAR');
 const old=structuredClone(before);delete old.saudiLocalization;old.settings.currency='USD';
 old.warehouses[0].name='Chicago Distribution Hub';old.warehouses[0].location='Chicago, IL';
 old.warehouses[1].name='My custom Saudi warehouse';
 old.users[1].name='My custom customer';old.users[1].address='240 Commerce Street, Dallas, TX';
 old.shipments[0].origin='Chicago Distribution Hub';old.shipments[0].destination=old.users[1].address;
 old.stock[0].qty=2000;
 memory.set('scms-state-v2',JSON.stringify(old));await m.init();
 const migrated=JSON.parse(JSON.stringify(m.data));
 assert.equal(migrated.settings.currency,'SAR');
 assert.equal(migrated.warehouses[0].name,'Riyadh Distribution Hub');
 assert.equal(migrated.warehouses[0].location,'Riyadh, Saudi Arabia');
 assert.equal(migrated.warehouses[1].name,'My custom Saudi warehouse');
 assert.equal(migrated.users[1].name,'My custom customer');
 assert.equal(migrated.shipments[0].origin,migrated.warehouses[0].name);
 assert.equal(migrated.shipments[0].destination,migrated.users[1].address);
 assert.deepEqual(migrated.stock,old.stock);
 assert.deepEqual(migrated.orders,old.orders);
 assert.deepEqual(migrated.users.map(u=>u.password),old.users.map(u=>u.password));
 await m.init();assert.deepEqual(JSON.parse(JSON.stringify(m.data)),migrated);
 console.log('Saudi seed and saved-data migration passed: custom records, credentials, orders and stock preserved; migration is idempotent.');
})().catch(e=>{console.error(e);process.exitCode=1;});
